export function getDaxCatalogStats() {
  const total = DAX_CATALOG.length;
  const complete = DAX_CATALOG.filter(c => c.status === 'complete').length;
  const partial = DAX_CATALOG.filter(c => c.status === 'partial').length;
  const unsupported = DAX_CATALOG.filter(c => c.status === 'unsupported').length;
  const pending = DAX_CATALOG.filter(c => c.status === 'pending_changelog').length;

  return {
    total,
    complete,
    partial,
    unsupported,
    pending,
    compliancePercentage: total > 0 ? Math.round((complete / total) * 100) : 0,
  };
}
